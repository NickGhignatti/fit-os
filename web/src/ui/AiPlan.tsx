import { useState, type ReactNode } from 'react';
import { useNavigate } from 'react-router-dom';
import { useContainer } from '../app/hooks';
import { readFileContents } from '../data/importFile';
import { importEnvelope } from '../data/importItem';
import { fixPrompt, ignoredPrompt } from '../data/importProblems';
import { SPEC_PATHS } from '../data/planSpecPaths';
import { catalogLinker } from '../domain/catalog';
import { useAsync, useToast } from './hooks';
import { Icons, Modal, type FabAction } from './kit';

/**
 * Workouts › + › Create with AI. The app has no AI of its own: it hands any AI chat the exact
 * format, as a prompt, and takes the answer back, pasted. The round trip is
 *   describe the plan → copy the prompt → the AI writes JSON → paste it → import,
 * and when the import fails, the problems go back to the AI in one tap, worded for it to fix.
 */

/** What came of the last paste. */
type Outcome =
  | { readonly kind: 'not_a_plan' }
  | { readonly kind: 'problems'; readonly lines: readonly string[] }
  /** Imported, but with fields the app does not know: the plan is there, and the AI can do better. */
  | { readonly kind: 'ignored'; readonly planId: string; readonly lines: readonly string[] };

const copyText = async (text: string): Promise<boolean> => {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
};

const ProblemList = ({ lines }: { lines: readonly string[] }) => (
  <ul className="small" style={{ margin: '4px 0 0', paddingLeft: 18 }}>
    {lines.map((line, i) => <li key={i}>{line}</li>)}
  </ul>
);

const AiPlanDialog = ({ onClose }: { onClose: () => void }) => {
  const { store, repos } = useContainer();
  const toast = useToast();
  const navigate = useNavigate();
  // The prompt embeds the JSON Schema, generated by a library the rest of the app does not need:
  // it is loaded when this dialog opens, so the Copy tap itself stays synchronous enough for
  // browsers that only allow clipboard writes right after a tap.
  const spec = useAsync(() => import('../data/planSpec'), []);
  const [goal, setGoal] = useState('');
  const [answer, setAnswer] = useState('');
  const [outcome, setOutcome] = useState<Outcome | null>(null);
  const [importing, setImporting] = useState(false);

  const prompt = () => (spec.state === 'ready' ? spec.value.aiPrompt(goal, window.location.origin) : '');
  const canShare = typeof navigator.share === 'function';

  const copy = (text: string, done: string) =>
    void copyText(text).then((ok) => toast(ok ? done : "Couldn't copy. Select the text and copy it by hand."));

  const openPlan = (id: string) => {
    onClose();
    navigate(`/workouts/plan/${id}`);
  };

  const importAnswer = async () => {
    setImporting(true);
    try {
      const contents = readFileContents(answer);
      if (contents.kind !== 'item' || contents.envelope.kind !== 'training_plan') return setOutcome({ kind: 'not_a_plan' });
      const result = await importEnvelope(store, contents.envelope, { linkExercise: catalogLinker(repos.exercises) });
      if (result.status === 'invalid') return setOutcome({ kind: 'problems', lines: result.problems });
      toast(`Imported workout plan “${result.title}”`);
      if (result.ignored.length > 0) return setOutcome({ kind: 'ignored', planId: result.id, lines: result.ignored });
      openPlan(result.id);
    } finally {
      setImporting(false);
    }
  };

  return (
    <Modal title="Create with AI" onClose={onClose}>
      <div className="stack">
        <section className="stack" aria-label="1. Ask the AI">
          <div className="title">1. Ask the AI</div>
          <label className="stack"><span className="small muted">What plan do you want?</span>
            <textarea className="field" rows={3} value={goal} onChange={(e) => setGoal(e.target.value)}
              placeholder="e.g. 3 days a week, no weights, jump higher for volleyball" /></label>
          <div className="actions" style={{ justifyContent: 'flex-start' }}>
            <button type="button" className="btn" disabled={spec.state !== 'ready'}
              onClick={() => copy(prompt(), 'Prompt copied. Paste it into your AI chat.')}>Copy prompt</button>
            {canShare && (
              <button type="button" className="btn secondary" disabled={spec.state !== 'ready'}
                onClick={() => void navigator.share({ text: prompt() }).catch(() => undefined)}>Share to an AI app</button>
            )}
          </div>
          <p className="small muted">
            The prompt tells the AI the exact format the app imports. Any chat works: ChatGPT, Claude, Gemini.
            {' '}<a href={`/${SPEC_PATHS.guide}`} target="_blank" rel="noreferrer">Format reference</a>
          </p>
        </section>

        <section className="stack" aria-label="2. Paste its answer">
          <div className="title">2. Paste its answer</div>
          <label className="stack"><span className="small muted">The AI's answer</span>
            <textarea className="field" rows={5} value={answer} spellCheck={false}
              onChange={(e) => { setAnswer(e.target.value); setOutcome(null); }}
              placeholder="Paste the whole reply: the JSON is found even with text around it." /></label>

          {outcome?.kind === 'not_a_plan' && (
            <p className="danger-text" role="alert">That doesn't look like a workout plan. Paste the AI's whole answer, with its JSON.</p>
          )}
          {outcome?.kind === 'problems' && (
            <div role="alert" className="stack">
              <p className="danger-text" style={{ margin: 0 }}>The plan can't be imported yet:</p>
              <ProblemList lines={outcome.lines} />
              <p className="small muted" style={{ margin: 0 }}>Send these back to the AI: it will fix them.</p>
            </div>
          )}
          {outcome?.kind === 'ignored' && (
            <div role="status" className="stack">
              <p style={{ margin: 0 }}>Imported. These fields were not understood, so they were left out:</p>
              <ProblemList lines={outcome.lines} />
            </div>
          )}

          <div className="actions">
            {outcome?.kind === 'problems' && (
              <button type="button" className="btn secondary" onClick={() => copy(fixPrompt(outcome.lines), 'Copied. Paste it into the same AI chat.')}>
                Copy for the AI
              </button>
            )}
            {outcome?.kind === 'ignored' ? (
              <>
                <button type="button" className="btn secondary" onClick={() => copy(ignoredPrompt(outcome.lines), 'Copied. Paste it into the same AI chat.')}>
                  Copy for the AI
                </button>
                <button type="button" className="btn" onClick={() => openPlan(outcome.planId)}>Open plan</button>
              </>
            ) : (
              <button type="button" className="btn" disabled={answer.trim() === '' || importing} onClick={() => void importAnswer()}>
                {importing ? 'Importing…' : 'Import plan'}
              </button>
            )}
          </div>
        </section>
      </div>
    </Modal>
  );
};

/** The "Create with AI" action of the Workouts +, and its dialog while open. */
export const useCreateWithAiAction = (): [FabAction, ReactNode] => {
  const [open, setOpen] = useState(false);
  return [
    { label: 'Create with AI', short: 'With AI', icon: Icons.ai, onSelect: () => setOpen(true) },
    open && <AiPlanDialog onClose={() => setOpen(false)} />,
  ];
};
